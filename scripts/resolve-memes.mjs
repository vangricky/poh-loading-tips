// Resolves item names in scripts/memes-source.txt to OSRS item ids and writes
// src/main/resources/com/pohloadingtips/memes.txt ("id,id|TOP|BOTTOM" per line).
import { readFileSync, writeFileSync } from "node:fs";
const UA = "poh-loading-tips meme build";
const src = readFileSync("scripts/memes-source.txt", "utf8").split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("#"));
const mapping = await (await fetch("https://prices.runescape.wiki/api/v1/osrs/mapping", { headers: { "User-Agent": UA } })).json();
const byName = new Map(mapping.map((m) => [m.name.toLowerCase(), m.id]));
async function wikiId(name) {
  const q = `bucket('infobox_item').select('item_id','item_name').where('item_name','${name.replace(/'/g, "\'")}').run()`;
  const j = await (await fetch(`https://oldschool.runescape.wiki/api.php?action=bucket&format=json&query=${encodeURIComponent(q)}`, { headers: { "User-Agent": UA } })).json();
  for (const row of j.bucket ?? []) for (const id of row.item_id ?? []) if (/^\d+$/.test(id)) return Number(id);
  return null;
}
const out = [];
const missing = [];
for (const line of src) {
  const [names, top, bottom] = line.split("|").map((s) => s.trim());
  const ids = [];
  for (const n of names.split(",").map((s) => s.trim())) {
    let id = n.startsWith("#") ? Number(n.slice(1)) : byName.get(n.toLowerCase()) ?? (await wikiId(n));
    if (id == null) missing.push(n);
    else ids.push(id);
  }
  if (ids.length && top && bottom) out.push(`${ids.join(",")}|${top}|${bottom}`);
}
writeFileSync("src/main/resources/com/pohloadingtips/memes.txt", "# Generated by scripts/resolve-memes.mjs from scripts/memes-source.txt\n" + out.join("\n") + "\n");
console.log(`${out.length} meme cards written; unresolved items: ${missing.join(", ") || "none"}`);
